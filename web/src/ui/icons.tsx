  bolt: ["....##..", "...##...", "..##....", ".######.", "....##..", "...##...", "..##....", ".##....."],
  star: ["...##...", "...##...", "########", ".######.", "..####..", ".##..##.", ".#....#.", "........"],
  bot: ["...##...", "........", ".######.", ".#.##.#.", ".######.", "..#..#..", ".######.", "........"],
  list: ["........", "##.#####", "........", "##.#####", "........", "##.#####", "........", "........"],
  bell: ["...##...", "..####..", ".######.", ".######.", ".######.", "########", "........", "...##..."],
  eye: ["........", "..####..", ".#....#.", "#..##..#", "#..##..#", ".#....#.", "..####..", "........"],
  check: ["........", ".......#", "......##", "#....##.", "##..##..", ".####...", "..##....", "........"],
